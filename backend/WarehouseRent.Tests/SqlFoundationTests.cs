using System.Net;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using WarehouseRent.Infrastructure.Persistence;

namespace WarehouseRent.Tests;

public sealed class SqlFoundationTests
{
    [Fact]
    [Trait("Category", "Sql")]
    public async Task Fresh_SQL_schema_migrates_seeds_repeatably_and_becomes_ready()
    {
        // Real SQL Server only. Override the server/auth template in CI; never borrow an existing database.
        var template = Environment.GetEnvironmentVariable("WAREHOUSERENT_TEST_SQL")
            ?? "Server=localhost;Integrated Security=True;Encrypt=True;TrustServerCertificate=True";
        var connection = new SqlConnectionStringBuilder(template)
        {
            InitialCatalog = $"WarehouseRent_Demo_Test_{Guid.NewGuid():N}",
        }.ConnectionString;
        await using var db = new AppDbContext(SqlConfiguration.Options(connection));
        try
        {
            // A reachable but empty database must not pass schema readiness.
            var catalog = new SqlConnectionStringBuilder(connection).InitialCatalog;
            await using (var admin = new SqlConnection(new SqlConnectionStringBuilder(connection) { InitialCatalog = "master" }.ConnectionString))
            {
                await admin.OpenAsync();
                await using var create = admin.CreateCommand();
                // catalog is generated above from a fixed prefix and Guid, never external input.
                create.CommandText = $"CREATE DATABASE [{catalog}]";
                await create.ExecuteNonQueryAsync();
            }
            await using var host = new WebApplicationFactory<Program>().WithWebHostBuilder(builder =>
            {
                builder.UseEnvironment("Testing");
                builder.UseSetting("ConnectionStrings:WarehouseRent", connection);
            });
            Assert.Equal(HttpStatusCode.ServiceUnavailable, (await host.CreateClient().GetAsync("/health/ready")).StatusCode);
            await DatabaseSetup.ApplyAsync(db, "Testing", connection, seedDemo: false);
            Assert.Equal(3, db.Database.GetCommandTimeout());
            Assert.NotEmpty(await db.Database.GetAppliedMigrationsAsync());
            Assert.Empty(await db.Database.GetPendingMigrationsAsync());
            Assert.Equal(0, await db.FoundationMarkers.CountAsync());
            await DatabaseSetup.ApplyAsync(db, "Demo", connection, seedDemo: true);
            await DatabaseSetup.ApplyAsync(db, "Demo", connection, seedDemo: true);
            Assert.Equal(3, db.Database.GetCommandTimeout());
            Assert.Equal(1, await db.FoundationMarkers.CountAsync());
            Assert.Equal("synthetic-demo-v1", (await db.FoundationMarkers.SingleAsync()).Id);
            var response = await host.CreateClient().GetAsync("/health/ready");
            Assert.Equal(HttpStatusCode.OK, response.StatusCode);

            // A SQL instance responding is insufficient if the application schema has been lost.
            await db.Database.ExecuteSqlRawAsync("DROP TABLE [FoundationMarkers]");
            Assert.Equal(HttpStatusCode.ServiceUnavailable, (await host.CreateClient().GetAsync("/health/ready")).StatusCode);
        }
        finally
        {
            // Only the unique database generated by this test can be deleted here.
            SqlConnection.ClearAllPools();
            await db.Database.EnsureDeletedAsync();
        }
    }

    [Fact]
    public async Task Production_seed_is_refused_before_database_access()
    {
        const string connection = "Server=127.0.0.1,1;Database=WarehouseRent_Demo;Integrated Security=True";
        await using var db = new AppDbContext(SqlConfiguration.Options(connection));
        var exception = await Assert.ThrowsAsync<InvalidOperationException>(() => DatabaseSetup.ApplyAsync(db, "Production", connection, seedDemo: true));
        Assert.Contains("Demo environment", exception.Message);
    }
}
